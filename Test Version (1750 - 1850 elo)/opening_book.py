def find_book_moves(engine):
    legal_moves = engine.get_all_legal_moves()
    
    if not legal_moves:
        return None
    
    move_count = len(engine.move_history)
    book_moves = []
    
    if move_count < 40:
        
        if move_count == 0:
            for move in legal_moves:
                if move in OPENING_BOOK['start']:
                    book_moves.append(move)
            if book_moves:
                return book_moves
        
        elif move_count == 1 and engine.turn == 'black':
            last_move = engine.move_history[-1]
            start, end = last_move['start'], last_move['end']
            
            key = None
            if end == (4, 4):   key = 'e4'
            elif end == (4, 3): key = 'd4'
            elif end == (5, 5): key = 'Nf3'
            elif end == (4, 2): key = 'c4'
            
            if key and key in OPENING_BOOK:
                for book_move in OPENING_BOOK[key]:
                    if book_move in legal_moves:
                        book_moves.append(book_move)
                if book_moves:
                    return book_moves
        
        # --- СПЕЦИФИЧЕСКИЕ ДЕБЮТНЫЕ ПОЗИЦИИ ---
        else:
            pos_key = None
            
            # Итальянская: e4 e5 Nf3 Nc6 Bc4
            if move_count >= 5:
                m = engine.move_history
                if (m[0]['end'] == (4,4) and m[1]['end'] == (4,4) and 
                    m[2]['end'] == (5,5) and m[3]['end'] == (2,2) and 
                    m[4]['end'] == (3,4)):
                    pos_key = 'italian'
                    # После 5...d5 или 5...Nf6 - защита двух коней
                    if move_count >= 6 and m[5]['end'] == (3,3):
                        pos_key = 'two_knights_ng5' if engine.turn == 'black' else 'two_knights'
            
            # Испанская: e4 e5 Nf3 Nc6 Bb5
            if move_count >= 5:
                m = engine.move_history
                if (m[0]['end'] == (4,4) and m[1]['end'] == (4,4) and 
                    m[2]['end'] == (5,5) and m[3]['end'] == (2,2) and 
                    m[4]['end'] == (3,1)):
                    pos_key = 'spanish'
            
            # Сицилианская: e4 c5 Nf3
            if move_count >= 3:
                m = engine.move_history
                if (m[0]['end'] == (4,4) and m[1]['end'] == (3,2) and 
                    m[2]['end'] == (5,5)):
                    pos_key = 'sicilian'
            
            # Французская: e4 e6 d4 d5
            if move_count >= 4:
                m = engine.move_history
                if (m[0]['end'] == (4,4) and m[1]['end'] == (2,4) and 
                    m[2]['end'] == (4,3) and m[3]['end'] == (3,3)):
                    pos_key = 'french'
            
            # Каро-Канн: e4 c6 d4 d5
            if move_count >= 4:
                m = engine.move_history
                if (m[0]['end'] == (4,4) and m[1]['end'] == (2,2) and 
                    m[2]['end'] == (4,3) and m[3]['end'] == (3,3)):
                    pos_key = 'caro_kann'
            
            # Ферзевый гамбит: d4 d5 c4
            if move_count >= 3:
                m = engine.move_history
                if (m[0]['end'] == (4,3) and m[1]['end'] == (3,3) and 
                    m[2]['end'] == (4,2)):
                    pos_key = 'queens_gambit'
            
            # Защита Нимцовича: d4 Nf6 c4 e6 Nc3 Bb4
            if move_count >= 6:
                m = engine.move_history
                if (m[0]['end'] == (4,3) and m[1]['end'] == (2,5) and 
                    m[2]['end'] == (4,2) and m[3]['end'] == (2,4) and 
                    m[4]['end'] == (5,2) and m[5]['end'] == (3,2)):
                    pos_key = 'nimzo_indian'
            
            # Староиндийская: d4 Nf6 c4 g6 Nc3 Bg7 e4 d6
            if move_count >= 8:
                m = engine.move_history
                if (m[0]['end'] == (4,3) and m[1]['end'] == (2,5) and 
                    m[2]['end'] == (4,2) and m[3]['end'] == (2,6) and 
                    m[4]['end'] == (5,2) and m[5]['end'] == (1,6) and 
                    m[6]['end'] == (4,4) and m[7]['end'] == (2,3)):
                    pos_key = 'kings_indian'
            
            # Английское начало: c4
            if move_count >= 1:
                m = engine.move_history
                if m[0]['end'] == (4,2):
                    pos_key = 'english'
            
            # Славянская: d4 d5 c4 c6
            if move_count >= 4:
                m = engine.move_history
                if (m[0]['end'] == (4,3) and m[1]['end'] == (3,3) and 
                    m[2]['end'] == (4,2) and m[3]['end'] == (2,2)):
                    pos_key = 'slav'
            
            # Голландская: d4 f5
            if move_count >= 2:
                m = engine.move_history
                if m[0]['end'] == (4,3) and m[1]['end'] == (3,5):
                    pos_key = 'dutch'
            
            if pos_key and pos_key in OPENING_BOOK:
                for book_move in OPENING_BOOK[pos_key]:
                    if book_move in legal_moves:
                        book_moves.append(book_move)
                if book_moves:
                    return book_moves
        
        if not book_moves:
            development_key = 'development' if engine.turn == 'white' else 'black_development'
            for book_move in OPENING_BOOK[development_key]:
                if book_move in legal_moves:
                    book_moves.append(book_move)
        
        for book_move in OPENING_BOOK['castling']:
            if book_move in legal_moves and book_move not in book_moves:
                book_moves.append(book_move)
        
        if book_moves:
            return book_moves
    
    return None